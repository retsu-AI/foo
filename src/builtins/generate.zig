//! `zig build catalog -Dmodels-dev=PATH`: turns a models.dev api.json snapshot into catalog.zig.
//! Usage: catalog-gen API_JSON > catalog.zig. Diagnostics go to stderr. Same input, same bytes.
const std = @import("std");
const cfg = @import("foo").config;
const records = @import("records.zig");

const max_input_bytes = 64 * 1024 * 1024;

const Provider = struct {
    id: []const u8,
    env: []const []const u8 = &.{},
    npm: ?[]const u8 = null,
    api: ?[]const u8 = null,
    models: std.json.ArrayHashMap(Model),
};

const Model = struct {
    id: []const u8,
    name: ?[]const u8 = null,
    type: ?[]const u8 = null,
    status: ?[]const u8 = null,
    tool_call: bool = false,
    modalities: ?struct { output: []const []const u8 = &.{} } = null,
    limit: struct { context: u32, output: u32 },
    provider: ?struct { npm: ?[]const u8 = null, api: ?[]const u8 = null } = null,
};

const Entry = struct {
    model: cfg.CatalogModel,

    fn lessThan(_: void, left: Entry, right: Entry) bool {
        return std.mem.order(u8, left.model.id, right.model.id) == .lt;
    }
};

pub fn main(init: std.process.Init) !void {
    var arena = std.heap.ArenaAllocator.init(init.gpa);
    defer arena.deinit();
    const a = arena.allocator();
    var args = try std.process.Args.Iterator.initAllocator(init.minimal.args, a);
    _ = args.skip();
    const path = args.next() orelse fail("usage: catalog-gen API_JSON (download https://models.dev/api.json)", .{});
    const bytes = std.Io.Dir.cwd().readFileAlloc(init.io, path, a, .limited(max_input_bytes)) catch |err|
        fail("cannot read {s}: {s}", .{ path, @errorName(err) });

    var out: std.Io.Writer.Allocating = .init(a);
    var diagnostics: std.Io.Writer.Allocating = .init(a);
    const result = generate(a, bytes, &out.writer, &diagnostics.writer);
    try std.Io.File.stderr().writeStreamingAll(init.io, diagnostics.written());
    result catch |err| fail("{s}", .{@errorName(err)});
    try std.Io.File.stdout().writeStreamingAll(init.io, out.written());
}

fn fail(comptime format: []const u8, args: anytype) noreturn {
    std.debug.print("catalog-gen: " ++ format ++ "\n", args);
    std.process.exit(1);
}

pub const Error = error{ OutOfMemory, InvalidInput, WriteFailed };

/// Writes the catalog for every record with a models.dev source. Fails when a record's provider
/// is missing, a required field is absent, or a per-model API lives on another origin.
pub fn generate(a: std.mem.Allocator, api_json: []const u8, out: *std.Io.Writer, log: *std.Io.Writer) Error!void {
    const parsed = std.json.parseFromSliceLeaky(std.json.Value, a, api_json, .{}) catch |err| switch (err) {
        error.OutOfMemory => return error.OutOfMemory,
        else => {
            try log.print("api.json is not valid JSON ({s})\n", .{@errorName(err)});
            return error.InvalidInput;
        },
    };
    if (parsed != .object) {
        try log.writeAll("api.json root is not an object\n");
        return error.InvalidInput;
    }
    try out.writeAll("// Generated by zig build catalog. Do not edit.\n");
    try out.writeAll("const M = @import(\"foo\").config.CatalogModel;\n");
    for (records.list) |record| {
        const source = record.modelsDevId() orelse continue;
        const raw = parsed.object.get(source) orelse {
            try log.print("{s}: provider {s} is missing from api.json\n", .{ record.id, source });
            return error.InvalidInput;
        };
        const provider = std.json.parseFromValueLeaky(Provider, a, raw, .{ .ignore_unknown_fields = true }) catch |err| switch (err) {
            error.OutOfMemory => return error.OutOfMemory,
            else => {
                try log.print("{s}: provider {s} has an unexpected shape ({s}); check models.{{id}}.limit.{{context,output}}\n", .{ record.id, source, @errorName(err) });
                return error.InvalidInput;
            },
        };
        const entries = try select(a, record, provider, log);
        try out.print("\npub const {f}: []const M = &.{{\n", .{std.zig.fmtId(source)});
        for (entries) |entry| {
            const m = entry.model;
            try out.print("    .{{ .id = \"{f}\", .name = \"{f}\", .output_limit = {d}, .context_limit = {d}", .{ std.zig.fmtString(m.id), std.zig.fmtString(m.name), m.output_limit, m.context_limit });
            if (m.route) |route| try out.print(", .route = .{{ .family = .{s}, .base_path = \"{f}\" }}", .{ @tagName(route.family), std.zig.fmtString(route.base_path) });
            try out.writeAll(" },\n");
        }
        try out.writeAll("};\n");
    }
}

fn select(a: std.mem.Allocator, record: records.Record, provider: Provider, log: *std.Io.Writer) Error![]Entry {
    var kept: std.ArrayList(Entry) = .empty;
    var skipped: usize = 0;
    for (provider.models.map.values()) |model| {
        const reason: ?[]const u8 = if (!model.tool_call)
            "no tool calls"
        else if (model.type != null and !std.mem.eql(u8, model.type.?, "chat"))
            "not a chat model"
        else if (!outputsText(model))
            "no text output"
        else if (model.status != null and (std.mem.eql(u8, model.status.?, "deprecated") or std.mem.eql(u8, model.status.?, "alpha")))
            model.status.?
        else if (!cfg.validId(model.id, .model))
            "invalid id"
        else
            null;
        if (reason) |why| {
            skipped += 1;
            try log.print("{s}: skip {s} ({s})\n", .{ record.id, model.id, why });
            continue;
        }
        const npm = if (model.provider) |p| p.npm else null;
        const family = if (npm) |name| familyOf(name) orelse {
            skipped += 1;
            try log.print("{s}: skip {s} (no codec for {s})\n", .{ record.id, model.id, name });
            continue;
        } else record.family;
        var entry: cfg.CatalogModel = .{
            .id = model.id,
            .name = model.name orelse model.id,
            .output_limit = model.limit.output,
            .context_limit = model.limit.context,
        };
        if (family != record.family) {
            const api = (if (model.provider) |p| p.api else null) orelse {
                try log.print("{s}: {s} speaks {s} but names no api URL\n", .{ record.id, model.id, @tagName(family) });
                return error.InvalidInput;
            };
            entry.route = .{ .family = family, .base_path = try routePath(record, model.id, api, log) };
        }
        try kept.append(a, .{ .model = entry });
    }
    std.mem.sort(Entry, kept.items, {}, Entry.lessThan);
    try log.print("{s}: {d} models, {d} skipped\n", .{ record.id, kept.items.len, skipped });
    if (findModel(kept.items, record.default_model) == null and findModel(record.extra_models, record.default_model) == null)
        try log.print("{s}: default_model {s} is not in the catalog; zig build check will fail until a human picks a new default\n", .{ record.id, record.default_model });
    for (provider.env) |name| {
        var listed = false;
        for (record.env) |known| listed = listed or std.mem.eql(u8, known, name);
        if (!listed) try log.print("{s}: models.dev names {s}; the record keeps {s}\n", .{ record.id, name, if (record.env.len == 0) "no variable" else record.env[0] });
    }
    return kept.items;
}

fn findModel(entries: anytype, id: []const u8) ?usize {
    for (entries, 0..) |entry, i| {
        const model_id = if (@TypeOf(entry) == Entry) entry.model.id else entry.id;
        if (std.mem.eql(u8, model_id, id)) return i;
    }
    return null;
}

fn outputsText(model: Model) bool {
    const modalities = model.modalities orelse return false;
    for (modalities.output) |kind| if (std.mem.eql(u8, kind, "text")) return true;
    return false;
}

fn familyOf(npm: []const u8) ?cfg.Family {
    const map = .{
        .{ "@ai-sdk/anthropic", cfg.Family.anthropic_messages },
        .{ "@ai-sdk/openai", cfg.Family.openai_responses },
        .{ "@ai-sdk/openai-compatible", cfg.Family.openai_chat },
    };
    inline for (map) |pair| if (std.mem.eql(u8, npm, pair[0])) return pair[1];
    return null;
}

/// The path of the model's API URL. It must share the record's origin, so a stored key never
/// goes to another host when the catalog says a model lives elsewhere.
fn routePath(record: records.Record, model_id: []const u8, api: []const u8, log: *std.Io.Writer) Error![]const u8 {
    const model_uri = std.Uri.parse(api) catch {
        try log.print("{s}: {s} has an invalid api URL\n", .{ record.id, model_id });
        return error.InvalidInput;
    };
    const base_uri = std.Uri.parse(record.base_url) catch unreachable;
    const host = model_uri.host orelse return mismatch(record, model_id, api, log);
    if (!std.ascii.eqlIgnoreCase(model_uri.scheme, base_uri.scheme) or
        !std.ascii.eqlIgnoreCase(host.percent_encoded, base_uri.host.?.percent_encoded) or
        model_uri.port != base_uri.port or model_uri.query != null or model_uri.fragment != null)
        return mismatch(record, model_id, api, log);
    const path = std.mem.trimEnd(u8, model_uri.path.percent_encoded, "/");
    if (path.len == 0 or path[0] != '/') return mismatch(record, model_id, api, log);
    return path;
}

fn mismatch(record: records.Record, model_id: []const u8, api: []const u8, log: *std.Io.Writer) Error {
    try log.print("{s}: {s} is served from {s}, not the record origin {s}\n", .{ record.id, model_id, api, record.base_url });
    return error.InvalidInput;
}
